// @tracked source preprocessor (POC)
// -----------------------------------------------------------------------------
// Expands the `@tracked` annotation into the runtime hooks it desugars to:
//
//   @tracked(a, b)              ->  SignalsReactAuto.useSignals([
//   <jsx>                             SignalsReactAuto.dep(a), SignalsReactAuto.dep(b)])
//                                   <jsx>
//
//   @tracked                    ->  SignalsReactAuto.useTracked(() => { <jsx> })
//   <jsx>
//
// `@tracked` is a valid-but-ignored ReScript attribute, so annotated sources
// still parse (and would simply render once, un-tracked) if this step is
// skipped. A production version would be a native ReScript PPX operating on the
// compiler AST; this text transform is the POC vehicle and has the usual
// caveats of source rewriting (see NOTE below).
//
// NOTE: brace matching for the bare `@tracked` form is naive — it counts `{`/`}`
// without skipping strings/comments. Keep bare-`@tracked` bodies to
// well-formed JSX/blocks. The explicit `@tracked(...)` form is a pure token
// replacement and has no such caveat.
// -----------------------------------------------------------------------------

const GENERATED_HEADER =
  "// GENERATED by scripts/tracked-preprocess.mjs from tests/tracked — do not edit.\n"

// Annotations must sit alone on their own line (after indentation), so
// occurrences inside `//` or `/* */` comments are never matched.
export function transform(src) {
  // Explicit form: @tracked(a, b, ...) -> useSignals([dep(a), dep(b), ...])
  let out = src.replace(/^([ \t]*)@tracked\(([^)]*)\)[ \t]*$/gm, (_m, indent, argStr) => {
    const args = argStr
      .split(",")
      .map(s => s.trim())
      .filter(Boolean)
    const deps = args.map(a => `SignalsReactAuto.dep(${a})`).join(", ")
    return `${indent}SignalsReactAuto.useSignals([${deps}])`
  })

  // Bare form: @tracked -> wrap the rest of the enclosing block in useTracked.
  let guard = 0
  let idx
  while ((idx = findBareTracked(out)) !== -1) {
    out = wrapBare(out, idx)
    if (++guard > 1000) throw new Error("tracked-preprocess: bare-form loop guard tripped")
  }
  return out
}

function findBareTracked(src) {
  // A bare `@tracked` alone on its own line. Returns the index of the `@`.
  const m = /^([ \t]*)@tracked[ \t]*$/m.exec(src)
  return m ? m.index + m[1].length : -1
}

function wrapBare(src, idx) {
  const open = src.lastIndexOf("{", idx)
  if (open === -1) throw new Error("tracked-preprocess: bare @tracked is not inside a block")
  let depth = 0
  let close = -1
  for (let i = open; i < src.length; i++) {
    if (src[i] === "{") depth++
    else if (src[i] === "}") {
      depth--
      if (depth === 0) {
        close = i
        break
      }
    }
  }
  if (close === -1) throw new Error("tracked-preprocess: unbalanced block for bare @tracked")
  const before = src.slice(0, idx)
  const body = src.slice(idx + "@tracked".length, close)
  const rest = src.slice(close)
  return `${before}SignalsReactAuto.useTracked(() => {${body}})${rest}`
}

// --- CLI: node tracked-preprocess.mjs <inDir> <outDir> -----------------------
// Runs only when invoked directly, not when imported by the unit test.
const invokedDirectly = import.meta.url === `file://${process.argv[1]}`
if (invokedDirectly) {
  const [, , inDir, outDir] = process.argv
  if (!inDir || !outDir) {
    console.error("usage: node tracked-preprocess.mjs <inDir> <outDir>")
    process.exit(1)
  }
  const { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } = await import("node:fs")
  const { join } = await import("node:path")

  mkdirSync(outDir, { recursive: true })
  const files = existsSync(inDir) ? readdirSync(inDir).filter(f => f.endsWith(".res")) : []
  for (const f of files) {
    const src = readFileSync(join(inDir, f), "utf8")
    writeFileSync(join(outDir, f), GENERATED_HEADER + transform(src))
  }
  console.log(`tracked-preprocess: expanded ${files.length} file(s) ${inDir} -> ${outDir}`)
}
